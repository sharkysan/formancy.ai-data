// The Content-Security-Policy each page of the composed stack's web front is
// served with (0083), in one place. deploy/web/nginx.conf sends it from a
// map this module writes (`node scripts/web-policies.mjs --write`), and
// scripts/web-policies.test.mjs fails when that map is not what this module
// writes, when a location of nginx.conf that serves files has no page here,
// and when anything in nginx.conf would keep the header from one; the
// studio's and the host page's browser gates serve each page with its
// policy from here (apps/*/scripts/browser/serve.mjs) and fail, in every
// browser, on anything the browser refuses under it; and the getting-started
// gate fails when the header nginx sends for a page is not this module's.
// So the policy every browser check ran under is the one the web image
// sends.
//
// Each policy is the examples page's (0069, scripts/demo-headers.mjs's
// POLICY) with the sources a page was measured needing, each named in its
// `allowed` with why: what policyProblems is told not to refuse, one source
// in one directive, never a looser rule for every page.

import { readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { contentSecurityPolicy, POLICY } from './demo-headers.mjs'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..')

/** A policy: 0069's, with each of `allowed`'s sources added to its directive, and nothing else changed. */
function allowing(allowed) {
  for (const name of Object.keys(allowed)) if (POLICY[name] === undefined) throw new Error(`${name} is no directive of 0069's policy`)
  return Object.freeze(Object.fromEntries(Object.entries(POLICY).map(([name, sources]) => [name, Object.freeze([...sources, ...(allowed[name] ?? [])])])))
}

/** A page of the web front: the location nginx.conf serves it at, the app it is built from, what its policy allows beyond 0069's, and the policy. */
function page(location, app, allowed) {
  return Object.freeze({ location, app, allowed: Object.freeze(allowed), policy: allowing(allowed) })
}

/**
 * The studio's policy allows nothing beyond 0069's. Served by its gate
 * under 0069's policy on 2026-10-17, the studio was refused nothing at any
 * step of its journey or its states under review, its version download
 * (0062) included, in Chromium, Firefox and WebKit (0083).
 */
export const STUDIO_ALLOWED = Object.freeze({})

/**
 * The host page's policy allows one source beyond 0069's: `'unsafe-inline'`
 * in style-src, for the style elements AG Grid Community creates to apply
 * its theme, as the live demo's policy does for the same page (0070).
 * Under 0069's policy those elements, and nothing else, were refused in
 * Chromium and Firefox on 2026-10-17, and the grid drew unstyled; the host
 * page's gate fails once a run when they no longer are (0083).
 * Everything else is 0069's: scripts from the page's own origin and nothing
 * inline or evaluated -- AG Grid's evaluator of column expressions given as
 * strings builds a function from one, and the host page gives none, which
 * the gate would hear refused -- and img-src, font-src and connect-src
 * still keep an injected style from loading anything from another host.
 */
export const HOST_ALLOWED = Object.freeze({ 'style-src': Object.freeze(["'unsafe-inline'"]) })

/** The pages, by the location nginx.conf serves each at. */
export const WEB_PAGES = Object.freeze({
  '/studio/': page('/studio/', 'apps/studio', STUDIO_ALLOWED),
  '/host/': page('/host/', 'apps/host', HOST_ALLOWED),
})

/** The header's value for the page nginx serves at `location`. */
export function pagePolicy(location) {
  const found = WEB_PAGES[location]
  if (found === undefined) throw new Error(`no page of the web front is served at ${location}`)
  return contentSecurityPolicy(found.policy)
}

export const NGINX_CONF = 'deploy/web/nginx.conf'

/** The variable the map sets and the server's add_header sends. */
export const POLICY_VARIABLE = '$formancy_content_security_policy'

const GENERATOR = 'scripts/web-policies.mjs'
const OPEN = `# generated by ${GENERATOR}; do not edit`
const END = '# end generated'

/** The map nginx.conf sends each page's policy from, keyed on the path: a page's location and everything below it, and nothing for any other path. */
export function policyMap() {
  const keys = Object.keys(WEB_PAGES).map((location) => `~^${location.replaceAll(/[.*+?^${}()|[\]\\]/g, '\\$&')}`)
  const width = Math.max('default'.length, ...keys.map((key) => key.length)) + 1
  const lines = Object.values(WEB_PAGES).map((each, at) => `    ${keys[at].padEnd(width)} "${contentSecurityPolicy(each.policy)}";`)
  return [`map $uri ${POLICY_VARIABLE} {`, ...lines, `    ${'default'.padEnd(width)} "";`, '}'].join('\n')
}

const lf = (text) => text.replaceAll('\r\n', '\n')

/** nginx.conf's text with its generated block's body replaced by policyMap(). Throws when the block is absent, repeated or unclosed. */
export function withPolicyMap(text) {
  const source = lf(text)
  const start = source.indexOf(OPEN)
  if (start === -1 || source.indexOf(OPEN, start + 1) !== -1) throw new Error(`${NGINX_CONF} must hold "${OPEN}" exactly once`)
  const end = source.indexOf(END, start)
  if (end === -1) throw new Error(`${NGINX_CONF}'s "${OPEN}" is never closed by "${END}"`)
  return `${source.slice(0, start)}${OPEN}\n${policyMap()}\n${source.slice(end)}`
}

/**
 * nginx's configuration text as a tree, as far as nginx.conf uses its
 * grammar: each directive `{ name, args, line }`, a block's directives in
 * `block`. `#` starts a comment outside quotes; a quoted argument may hold
 * spaces, `;`, `{` and `}`, and a backslash escapes the next character.
 */
export function parseNginx(text) {
  const root = []
  const stack = [root]
  let words = []
  let line = 1
  let first = 1
  let at = 0
  const source = lf(text)
  while (at < source.length) {
    const char = source[at]
    if (char === '\n') line += 1
    if (/\s/.test(char)) {
      at += 1
      continue
    }
    if (char === '#') {
      while (at < source.length && source[at] !== '\n') at += 1
      continue
    }
    if (char === ';' || char === '{') {
      if (words.length === 0) throw new Error(`line ${String(line)}: "${char}" with no directive before it`)
      const directive = { name: words[0], args: words.slice(1), line: first }
      stack.at(-1).push(directive)
      if (char === '{') {
        directive.block = []
        stack.push(directive.block)
      }
      words = []
      at += 1
      continue
    }
    if (char === '}') {
      if (words.length > 0 || stack.length === 1) throw new Error(`line ${String(line)}: "}" that closes nothing, or after an unfinished directive`)
      stack.pop()
      at += 1
      continue
    }
    if (words.length === 0) first = line
    let word = ''
    const quote = char === '"' || char === "'" ? char : null
    if (quote !== null) at += 1
    while (at < source.length) {
      const next = source[at]
      if (quote === null ? /[\s;{}]/.test(next) : next === quote) break
      if (next === '\\' && at + 1 < source.length) {
        word += source[at + 1]
        at += 2
        continue
      }
      if (next === '\n') line += 1
      word += next
      at += 1
    }
    if (quote !== null) {
      if (source[at] !== quote) throw new Error(`line ${String(first)}: a quoted argument never closed`)
      at += 1
    }
    words.push(word)
  }
  if (words.length > 0 || stack.length > 1) throw new Error('the configuration ends inside a directive or a block')
  return root
}

/** Every directive named `name` in `directives` and the blocks below them. */
const below = (directives, name) => directives.flatMap((each) => [...(each.name === name ? [each] : []), ...below(each.block ?? [], name)])

/**
 * What a nginx `map` block's entries give `value`, as nginx chooses: an
 * exact string first, then the regular expressions in their order, `~`
 * minding case and `~*` not, then `default`, else the empty string.
 */
export function mapValue(entries, value) {
  const exact = entries.find(([key]) => !key.startsWith('~') && key !== 'default' && key === value)
  if (exact !== undefined) return exact[1]
  for (const [key, given] of entries) {
    if (!key.startsWith('~')) continue
    const insensitive = key.startsWith('~*')
    if (new RegExp(key.slice(insensitive ? 2 : 1), insensitive ? 'i' : '').test(value)) return given
  }
  return entries.find(([key]) => key === 'default')?.[1] ?? ''
}

/** A location's prefix, its modifier aside. */
const prefixOf = (location) => location.args.at(-1)

/**
 * What is wrong with how nginx.conf's text `text` sends the pages their
 * policies, one sentence each, none when nothing is:
 *
 * - its generated map is what policyMap() writes;
 * - every location that serves files, by `alias` or `root`, is a page here,
 *   and every page here is a location that serves files;
 * - the map, as nginx reads it, gives each page's location, its index.html
 *   and its hashed assets that page's policy;
 * - the server of each such location sends the map's variable as
 *   Content-Security-Policy, `always`, so a 404 under the page carries it
 *   too; and neither the location nor anything inside it has an add_header
 *   of its own, which in nginx drops every add_header of the server for
 *   that location.
 */
export function nginxPolicyProblems(text) {
  const problems = []
  try {
    if (withPolicyMap(text) !== lf(text)) problems.push(`${NGINX_CONF}'s policy map is not what ${GENERATOR} writes: run \`node ${GENERATOR} --write\``)
  } catch (error) {
    problems.push(error.message)
  }
  const tree = parseNginx(text)
  const maps = tree.filter((each) => each.name === 'map' && each.args[1] === POLICY_VARIABLE)
  if (maps.length !== 1) return [...problems, `${NGINX_CONF} must set ${POLICY_VARIABLE} by exactly one map; it has ${String(maps.length)}`]
  const entries = maps[0].block.map((entry) => [entry.name, entry.args[0] ?? ''])
  if (maps[0].args[0] !== '$uri') problems.push(`${POLICY_VARIABLE}'s map is keyed on ${maps[0].args[0]}, not $uri, the path a location is chosen by`)

  const served = new Set()
  for (const server of tree.filter((each) => each.name === 'server')) {
    const locations = server.block.filter((each) => each.name === 'location')
    const pages = locations.filter((location) => below(location.block, 'alias').length + below(location.block, 'root').length > 0)
    if (pages.length === 0) continue
    const sends = server.block.filter((each) => each.name === 'add_header' && each.args[0]?.toLowerCase() === 'content-security-policy')
    const listens = below(server.block, 'listen').map((each) => each.args[0]).join(', ')
    if (!sends.some((each) => each.args[1] === POLICY_VARIABLE && each.args[2] === 'always')) {
      problems.push(`the server on ${listens} serves ${pages.map(prefixOf).join(' and ')} and has no "add_header Content-Security-Policy ${POLICY_VARIABLE} always;" of its own`)
    }
    for (const location of pages) {
      const prefix = prefixOf(location)
      served.add(prefix)
      const own = below(location.block, 'add_header')
      if (own.length > 0) problems.push(`location ${prefix} has an add_header of its own (line ${String(own[0].line)}), which drops every add_header of its server there, the policy among them`)
      const known = WEB_PAGES[prefix]
      if (known === undefined) {
        problems.push(`location ${prefix} serves files, and ${GENERATOR} has no policy for a page there`)
        continue
      }
      const wanted = contentSecurityPolicy(known.policy)
      for (const path of [prefix, `${prefix}index.html`, `${prefix}assets/index-a1b2c3.js`]) {
        const sent = mapValue(entries, path)
        if (sent !== wanted) problems.push(`${NGINX_CONF} sends ${path} ${sent === '' ? 'no policy' : `"${sent}"`}, not ${GENERATOR}'s "${wanted}"`)
      }
    }
  }
  for (const location of Object.keys(WEB_PAGES)) if (!served.has(location)) problems.push(`${GENERATOR} has a policy for ${location}, and no location of ${NGINX_CONF} serves files there`)
  return problems
}

// `node scripts/web-policies.mjs --write` rewrites nginx.conf's map; without
// it, the map is printed. Compared by real path, as scripts/demo.mjs is run.
if (process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  if (process.argv.includes('--write')) {
    const file = join(repo, NGINX_CONF)
    writeFileSync(file, withPolicyMap(readFileSync(file, 'utf8')), 'utf8')
    console.log(`${NGINX_CONF}: the policy map of ${Object.keys(WEB_PAGES).join(' and ')}`)
  } else {
    process.stdout.write(`${policyMap()}\n`)
  }
}
