import { generateDemoData } from './generate.js'
import { demoDataProblems } from './invariants.js'
import type { DemoData } from './model.js'
import { decimal } from './model.js'

/*
 * The demo's rows as PostgreSQL, loaded after the fixture's postgres.sql in
 * one transaction the loader opens: the image's `psql -1`, or the
 * integration test's transaction. The fixture's schema stays exactly as the
 * adapter suites load it; its rows -- the edge cases those suites need, an
 * order numbered 2^53 + 1, an employee whose manager does not exist -- are
 * replaced by these.
 *
 * Every value is the generator's own, from its word lists and numbers, never
 * input; a quote is doubled all the same.
 */

const text = (value: string): string => `'${value.replaceAll("'", "''")}'`
const orNull = <T>(value: T | null, write: (value: T) => string): string => (value === null ? 'null' : write(value))
/** An instant in UTC, to the second: `2026-09-30 08:14:00+00`. */
const instant = (time: number): string => text(new Date(time).toISOString().replace('T', ' ').replace(/\.\d{3}Z$/, '+00'))

/** One insert of every row, a row a line, or nothing for no rows: `values ;` is a syntax error. */
function insert(table: string, columns: readonly string[], rows: ReadonlyArray<readonly string[]>, overriding = false): string[] {
  if (rows.length === 0) return []
  return [`insert into ${table} (${columns.join(', ')})${overriding ? ' overriding system value' : ''} values`, `${rows.map((row) => `  (${row.join(', ')})`).join(',\n')};`, '']
}

/** The SQL that replaces the fixture's rows with `data`. */
export function renderDemoSql(data: DemoData): string {
  return [
    "-- The live demo's sample data. GENERATED by apps/live-demo/src/data -- do not edit.",
    '--',
    "-- Loaded after packages/data-fixtures/fixtures/postgres.sql, in the loader's one",
    "-- transaction: the fixture's schema as it is, the fixture's rows replaced.",
    '',
    // The file is UTF-8 (Zürich, Liège), whatever the session's default.
    "set client_encoding = 'UTF8';",
    '',
    // The order cascades to its lines, deliveries and parcels; then what the orders referenced.
    'delete from sales."order";',
    'delete from sales.shipment;',
    'delete from sales.customer;',
    'delete from sales.employee;',
    '',
    ...insert(
      'sales.country',
      ['iso_code', 'name'],
      data.countries.map((country) => [text(country.isoCode), text(country.name)]),
    ),
    ...insert(
      'sales.employee',
      ['id', 'name', 'manager_id'],
      data.employees.map((employee) => [String(employee.id), text(employee.name), orNull(employee.managerId, String)]),
    ),
    // The fixture adds this key NOT VALID over its orphan; with the orphan
    // gone, the key is validated, which proves the new hierarchy holds.
    'alter table sales.employee validate constraint fk_employee_manager;',
    '',
    ...insert(
      'sales.customer',
      ['tenant_id', 'customer_no', 'name', 'country_code', 'credit_limit', 'active', 'created_at'],
      data.customers.map((customer) => [
        String(customer.tenantId),
        String(customer.customerNo),
        text(customer.name),
        text(customer.countryCode),
        orNull(customer.creditLimitCents, (cents) => decimal(cents, 2)),
        String(customer.active),
        instant(customer.createdAt),
      ]),
    ),
    ...insert(
      'sales."order"',
      ['id', 'tenant_id', 'customer_no', 'order_date', 'status', 'amount', 'notes', '"group"', 'created_by', 'approved_by'],
      data.orders.map((order) => [
        String(order.id),
        String(order.tenantId),
        String(order.customerNo),
        text(order.orderDate),
        text(order.status),
        decimal(order.amountCents, 4),
        orNull(order.notes, text),
        'null',
        String(order.createdBy),
        orNull(order.approvedBy, String),
      ]),
      true,
    ),
    ...insert(
      'sales.order_line',
      ['order_id', 'line_no', 'quantity', 'unit_price'],
      data.lines.map((line) => [String(line.orderId), String(line.lineNo), String(line.quantity), decimal(line.unitPriceCents, 2)]),
    ),
    ...insert(
      'sales.delivery',
      ['id', 'tenant_id', 'order_id', 'carrier', 'shipped_at'],
      data.deliveries.map((delivery) => [text(delivery.id), String(delivery.tenantId), String(delivery.orderId), text(delivery.carrier), instant(delivery.shippedAt)]),
    ),
    ...insert(
      'sales.parcel',
      ['id', 'delivery_id', 'label'],
      data.parcels.map((parcel) => [String(parcel.id), text(parcel.deliveryId), text(parcel.label)]),
      true,
    ),
    // Past the explicit keys, so the first order a visitor creates is not order 1 again.
    `alter table sales."order" alter column id restart with ${String(Math.max(0, ...data.orders.map((order) => order.id)) + 1)};`,
    `alter table sales.parcel alter column id restart with ${String(Math.max(0, ...data.parcels.map((parcel) => parcel.id)) + 1)};`,
    '',
  ].join('\n')
}

/** The SQL for `data`, the generated rows unless given others; refused, naming every problem, when they break an invariant. */
export function demoSql(data: DemoData = generateDemoData()): string {
  const problems = demoDataProblems(data)
  if (problems.length > 0) throw new Error(`The demo data breaks its invariants:\n${problems.map((problem) => `  - ${problem}`).join('\n')}`)
  return renderDemoSql(data)
}
